@router.post(
    "/videos/analyze"
)
async def analyze_uploaded_video(
    file: UploadFile = File(...),
):
    """
    Legacy CCTV analysis endpoint.

    This endpoint does not belong to a
    specific database case.

    It remains available for backward compatibility.
    """

    # =====================================================
    # 1. VALIDATE FILE
    # =====================================================

    if not file.filename:

        raise HTTPException(
            status_code=400,
            detail="No video file provided.",
        )

    original_filename = (
        Path(
            file.filename
        ).name
    )

    extension = (
        Path(
            original_filename
        )
        .suffix
        .lower()
    )

    if extension not in ALLOWED_VIDEO_EXTENSIONS:

        raise HTTPException(
            status_code=400,
            detail=(
                "Unsupported video format. "
                f"Allowed: "
                f"{sorted(ALLOWED_VIDEO_EXTENSIONS)}"
            ),
        )

    # =====================================================
    # 2. CREATE ANALYSIS ID
    # =====================================================

    analysis_id = (
        datetime.now().strftime(
            "%Y%m%d_%H%M%S"
        )
        + "_"
        + uuid4().hex[:8]
    )

    # =====================================================
    # 3. VIDEO PATH
    # =====================================================

    video_path = (
        VIDEOS_DIR
        / (
            f"{analysis_id}_"
            f"{original_filename}"
        )
    )

    # =====================================================
    # 4. RESULT DIRECTORY
    # =====================================================

    output_directory = (
        RESULTS_DIR
        / analysis_id
    )

    output_directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    # =====================================================
    # 5. SAVE + ANALYZE
    # =====================================================

    try:

        await save_uploaded_video(
            file,
            video_path,
        )

        result = analyze_cctv_video(

            video_path=video_path,

            output_directory=(
                output_directory
            ),

            frame_skip=5,
        )

        result = make_json_safe(
            result
        )

        # -------------------------------------------------
        # Find actual matcher results
        # -------------------------------------------------

        results_path = (
            find_matcher_results_path(
                result,
                output_directory,
            )
        )

        results_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        # -------------------------------------------------
        # Save results
        # -------------------------------------------------

        with results_path.open(
            "w",
            encoding="utf-8",
        ) as json_file:

            json.dump(
                result,
                json_file,
                indent=4,
                ensure_ascii=False,
            )

        return {

            "success":
                True,

            "analysis_id":
                analysis_id,

            "results":
                result,

            "results_file":
                str(results_path),
        }

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail=(
                "CCTV analysis failed: "
                f"{exc}"
            ),
        )