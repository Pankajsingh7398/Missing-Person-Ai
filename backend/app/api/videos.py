@router.get(
    "/cases/{case_id}/analyses/{analysis_id}/evidence/{filename}"
)
def get_evidence_image(
    case_id: int,
    analysis_id: str,
    filename: str,
    db: Session = Depends(get_db),
):
    """
    Return one evidence image.

    IMPORTANT:

    Evidence images are stored in the SAME directory
    as the actual matcher results.json.

    Example:

    cctv_results/
        1/
            20260813_205934_e80d4ba7/
                20260813_212539/
                    results.json
                    match_0001.jpg
                    match_0002.jpg
                    match_0005.jpg
    """

    print()
    print("=" * 60)
    print("EVIDENCE IMAGE REQUEST")
    print("=" * 60)

    print(
        f"Case ID: {case_id}"
    )

    print(
        f"Analysis ID: {analysis_id}"
    )

    # -----------------------------------------------------
    # Validate filename
    # -----------------------------------------------------

    safe_filename = (
        get_safe_evidence_filename(
            filename
        )
    )

    print(
        f"Requested: {safe_filename}"
    )

    # -----------------------------------------------------
    # Find analysis
    # -----------------------------------------------------

    analysis = get_analysis_or_404(
        case_id,
        analysis_id,
        db,
    )

    # -----------------------------------------------------
    # Find actual results directory
    # -----------------------------------------------------

    results_directory = (
        get_analysis_results_directory(
            analysis
        )
    )

    evidence_path = (
        results_directory
        / safe_filename
    )

    print(
        f"Found: {evidence_path}"
    )

    print("=" * 60)

    # -----------------------------------------------------
    # Verify file
    # -----------------------------------------------------

    if not evidence_path.exists():

        raise HTTPException(
            status_code=404,
            detail=(
                "Evidence image not found: "
                f"{safe_filename}"
            ),
        )

    if not evidence_path.is_file():

        raise HTTPException(
            status_code=404,
            detail=(
                "Evidence path is not a file."
            ),
        )

    # -----------------------------------------------------
    # Return image
    # -----------------------------------------------------

    return FileResponse(

        path=str(
            evidence_path
        ),

        media_type="image/jpeg",

        filename=safe_filename,
    )


