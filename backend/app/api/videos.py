@router.post(
    "/cases/{case_id}/videos"
)
async def analyze_case_video(
    case_id: int,
    file: UploadFile = File(
        ...,
        description=(
            "Upload a CCTV video "
            "for this missing-person case"
        ),
    ),
    db: Session = Depends(get_db),
):
    """
    Upload and analyze a CCTV video against
    the reference profile belonging to a
    specific missing-person case.
    """

    # =====================================================
    # 1. FIND CASE
    # =====================================================

    case = get_case_or_404(
        case_id,
        db,
    )

    print()
    print("=" * 60)
    print("CASE FOUND")
    print("=" * 60)
    print(
        f"Case ID: {case.id}"
    )
    print(
        f"Name: {case.name}"
    )
    print("=" * 60)

    # =====================================================
    # 2. VALIDATE VIDEO
    # =====================================================

    if not file.filename:

        raise HTTPException(
            status_code=400,
            detail="No video file provided.",
        )

    original_filename = (
        Path(
            file.filename
        ).name
    )

    extension = (
        Path(
            original_filename
        )
        .suffix
        .lower()
    )

    if extension not in ALLOWED_VIDEO_EXTENSIONS:

        raise HTTPException(
            status_code=400,
            detail=(
                "Unsupported video format. "
                f"Allowed: "
                f"{sorted(ALLOWED_VIDEO_EXTENSIONS)}"
            ),
        )

    # =====================================================
    # 3. FIND REFERENCE PROFILE
    # =====================================================

    reference_profile_path = (
        DATA_DIR
        / "missing_persons"
        / str(case.id)
        / "references"
        / "reference_profile.npz"
    )

    if not reference_profile_path.exists():

        raise HTTPException(
            status_code=400,
            detail=(
                "Reference profile not found for "
                f"case {case.id}. "
                "Upload reference images first."
            ),
        )

    print()
    print(
        f"Reference profile: "
        f"{reference_profile_path}"
    )

    # =====================================================
    # 4. CREATE ANALYSIS ID
    # =====================================================

    analysis_id = (
        datetime.now().strftime(
            "%Y%m%d_%H%M%S"
        )
        + "_"
        + uuid4().hex[:8]
    )

    # =====================================================
    # 5. CREATE VIDEO DIRECTORY
    # =====================================================

    case_video_directory = (
        VIDEOS_DIR
        / str(case.id)
    )

    case_video_directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    # =====================================================
    # 6. UNIQUE VIDEO NAME
    # =====================================================

    video_filename = (
        f"{analysis_id}_"
        f"{original_filename}"
    )

    video_path = (
        case_video_directory
        / video_filename
    )

    # =====================================================
    # 7. CREATE OUTER RESULT DIRECTORY
    # =====================================================

    analysis_result_directory = (
        RESULTS_DIR
        / str(case.id)
        / analysis_id
    )

    analysis_result_directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    # =====================================================
    # 8. SAVE VIDEO
    # =====================================================

    try:

        print()
        print("=" * 60)
        print("CCTV VIDEO UPLOAD")
        print("=" * 60)

        print(
            f"Case ID: {case.id}"
        )

        print(
            f"Case Name: {case.name}"
        )

        print(
            f"Analysis ID: {analysis_id}"
        )

        print(
            f"Original video: "
            f"{original_filename}"
        )

        print(
            f"Saving video to: "
            f"{video_path}"
        )

        await save_uploaded_video(
            file,
            video_path,
        )

        print(
            "Video saved successfully."
        )

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail=(
                "Could not save video: "
                f"{exc}"
            ),
        )

    # =====================================================
    # 9. CREATE DATABASE VIDEO RECORD
    # =====================================================

    cctv_video = CCTVVideo(
        case_id=case.id,
        original_filename=(
            original_filename
        ),
        stored_path=str(
            video_path
        ),
        status="processing",
    )

    db.add(
        cctv_video
    )

    db.commit()

    db.refresh(
        cctv_video
    )

    print(
        f"CCTV database ID: "
        f"{cctv_video.id}"
    )

    # =====================================================
    # 10. RUN CCTV ANALYSIS
    # =====================================================

    try:

        print()
        print("=" * 60)
        print("STARTING CCTV ANALYSIS")
        print("=" * 60)

        print(
            f"Case: {case.name}"
        )

        print(
            f"Case ID: {case.id}"
        )

        print(
            f"Profile: "
            f"{reference_profile_path}"
        )

        print(
            f"Video: "
            f"{video_path}"
        )

        print(
            f"Results: "
            f"{analysis_result_directory}"
        )

        result = analyze_cctv_video(

            video_path=video_path,

            output_directory=(
                analysis_result_directory
            ),

            frame_skip=5,

            reference_profile_path=(
                reference_profile_path
            ),
        )

        print()
        print("=" * 60)
        print("CCTV ANALYSIS COMPLETE")
        print("=" * 60)

    except Exception as exc:

        cctv_video.status = "failed"

        db.commit()

        print()
        print("=" * 60)
        print("CCTV ANALYSIS FAILED")
        print("=" * 60)

        print(
            str(exc)
        )

        raise HTTPException(
            status_code=500,
            detail=(
                "CCTV analysis failed: "
                f"{exc}"
            ),
        )

    # =====================================================
    # 11. MAKE RESULT JSON SAFE
    # =====================================================

    result = make_json_safe(
        result
    )

    # =====================================================
    # 12. FIND ACTUAL MATCHER RESULTS.JSON
    # =====================================================

    results_path = (
        find_matcher_results_path(
            result,
            analysis_result_directory,
        )
    )

    # =====================================================
    # 13. ADD APPLICATION INFORMATION
    # =====================================================

    result["case_id"] = (
        case.id
    )

    result["case_name"] = (
        case.name
    )

    result["analysis_id"] = (
        analysis_id
    )

    result["video_path"] = (
        str(video_path)
    )

    result["reference_profile"] = (
        str(reference_profile_path)
    )

    result["results_path"] = (
        str(results_path)
    )

    result["cctv_video_id"] = (
        cctv_video.id
    )

    # =====================================================
    # 14. SAVE FINAL RESULTS.JSON
    # =====================================================

    try:

        results_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        with results_path.open(
            "w",
            encoding="utf-8",
        ) as json_file:

            json.dump(
                result,
                json_file,
                indent=4,
                ensure_ascii=False,
            )

    except Exception as exc:

        cctv_video.status = "failed"

        db.commit()

        raise HTTPException(
            status_code=500,
            detail=(
                "Analysis completed, "
                "but results could not "
                f"be saved: {exc}"
            ),
        )

    # =====================================================
    # 15. CALCULATE SUMMARY
    # =====================================================

    matches = result.get(
        "matches",
        [],
    )

    sightings = result.get(
        "sightings",
        [],
    )

    potential_matches = int(
        result.get(
            "potential_matches",
            len(matches),
        )
    )

    confirmed_sightings = int(
        result.get(
            "confirmed_sightings",
            len(sightings),
        )
    )

    # =====================================================
    # 16. BEST SIMILARITY
    # =====================================================

    best_similarity = None

    if sightings:

        similarities = [
            float(
                item["best_similarity"]
            )
            for item in sightings
            if item.get(
                "best_similarity"
            ) is not None
        ]

        if similarities:

            best_similarity = max(
                similarities
            )

    elif matches:

        similarities = [
            float(
                item["similarity"]
            )
            for item in matches
            if item.get(
                "similarity"
            ) is not None
        ]

        if similarities:

            best_similarity = max(
                similarities
            )

    # =====================================================
    # 17. CREATE CCTV ANALYSIS RECORD
    # =====================================================

    cctv_analysis = CCTVAnalysis(

        case_id=case.id,

        video_id=cctv_video.id,

        analysis_id=analysis_id,

        status="completed",

        potential_matches=(
            potential_matches
        ),

        confirmed_sightings=(
            confirmed_sightings
        ),

        best_similarity=(
            best_similarity
        ),

        results_path=str(
            results_path
        ),
    )

    db.add(
        cctv_analysis
    )

    # =====================================================
    # 18. UPDATE VIDEO STATUS
    # =====================================================

    cctv_video.status = (
        "completed"
    )

    db.commit()

    db.refresh(
        cctv_analysis
    )

    # =====================================================
    # 19. FINAL LOG
    # =====================================================

    print()
    print("=" * 60)
    print("ANALYSIS FINISHED")
    print("=" * 60)

    print(
        f"Case ID: {case.id}"
    )

    print(
        f"Video ID: {cctv_video.id}"
    )

    print(
        f"Analysis DB ID: "
        f"{cctv_analysis.id}"
    )

    print(
        f"Analysis ID: "
        f"{analysis_id}"
    )

    print(
        f"Potential matches: "
        f"{potential_matches}"
    )

    print(
        f"Confirmed sightings: "
        f"{confirmed_sightings}"
    )

    print(
        f"Best similarity: "
        f"{best_similarity}"
    )

    print(
        f"Results: "
        f"{results_path}"
    )

    print("=" * 60)

    # =====================================================
    # 20. RESPONSE
    # =====================================================

    return {

        "success": True,

        "case_id":
            case.id,

        "case_name":
            case.name,

        "cctv_video_id":
            cctv_video.id,

        "analysis_db_id":
            cctv_analysis.id,

        "analysis_id":
            analysis_id,

        "status":
            "completed",

        "video":
            str(video_path),

        "reference_profile":
            str(reference_profile_path),

        "potential_matches":
            potential_matches,

        "confirmed_sightings":
            confirmed_sightings,

        "best_similarity":
            best_similarity,

        "results":
            result,

        "results_file":
            str(results_path),
    }


