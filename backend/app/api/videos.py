async def save_uploaded_video(
    file: UploadFile,
    output_path: Path,
):
    """
    Save uploaded CCTV video in chunks.

    Large CCTV videos are not loaded
    completely into RAM.
    """

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    try:

        with output_path.open("wb") as output_file:

            while True:

                chunk = await file.read(
                    1024 * 1024
                )

                if not chunk:
                    break

                output_file.write(
                    chunk
                )

    finally:

        await file.close()


# =========================================================
# JSON SAFE CONVERSION
# =========================================================

def make_json_safe(value):
    """
    Convert Path objects and nested structures
    into JSON-compatible values.
    """

    if isinstance(value, Path):

        return str(value)

    if isinstance(value, dict):

        return {
            key: make_json_safe(item)
            for key, item in value.items()
        }

    if isinstance(value, list):

        return [
            make_json_safe(item)
            for item in value
        ]

    return value


# =========================================================
# LOAD RESULTS JSON
# =========================================================

def load_results_json(
    results_path: Path,
):
    """
    Load a previously saved CCTV analysis results.json.
    """

    if not results_path.exists():

        raise HTTPException(
            status_code=404,
            detail=(
                "Analysis results file not found."
            ),
        )

    try:

        with results_path.open(
            "r",
            encoding="utf-8",
        ) as json_file:

            return json.load(
                json_file
            )

    except json.JSONDecodeError as exc:

        raise HTTPException(
            status_code=500,
            detail=(
                "Analysis results JSON is invalid: "
                f"{exc}"
            ),
        )

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail=(
                "Could not read analysis results: "
                f"{exc}"
            ),
        )


# =========================================================
# FIND ACTUAL MATCHER RESULT DIRECTORY
# =========================================================

def find_matcher_results_path(
    result: dict,
    fallback_directory: Path,
):
    """
    Find the actual results.json generated by
    cctv_matcher.py.

    The matcher creates:

    cctv_results/
        <case_id>/
            <outer_analysis_id>/
                <matcher_analysis_id>/
                    results.json

    The matcher returns result_directory/result_file,
    so those paths are preferred.
    """

    # -----------------------------------------------------
    # 1. Matcher result_directory
    # -----------------------------------------------------

    matcher_directory = result.get(
        "result_directory"
    )

    if matcher_directory:

        matcher_directory = Path(
            matcher_directory
        )

        matcher_results = (
            matcher_directory
            / "results.json"
        )

        if matcher_results.exists():

            return matcher_results

    # -----------------------------------------------------
    # 2. Matcher result_file
    # -----------------------------------------------------

    matcher_results_file = result.get(
        "result_file"
    )

    if matcher_results_file:

        matcher_results_file = Path(
            matcher_results_file
        )

        if matcher_results_file.exists():

            return matcher_results_file

    # -----------------------------------------------------
    # 3. Fallback
    # -----------------------------------------------------

    return (
        fallback_directory
        / "results.json"
    )


# =========================================================
# FIND CASE
# =========================================================

def get_case_or_404(
    case_id: int,
    db: Session,
):
    """
    Return a case or raise HTTP 404.
    """

    case = (
        db.query(MissingPersonCase)
        .filter(
            MissingPersonCase.id == case_id
        )
        .first()
    )

    if case is None:

        raise HTTPException(
            status_code=404,
            detail="Case not found",
        )

    return case


# =========================================================
# FIND ANALYSIS
# =========================================================

def get_analysis_or_404(
    case_id: int,
    analysis_id: str,
    db: Session,
):
    """
    Return a CCTV analysis belonging to
    the requested case.
    """

    analysis = (
        db.query(CCTVAnalysis)
        .filter(
            CCTVAnalysis.case_id == case_id,
            CCTVAnalysis.analysis_id == analysis_id,
        )
        .first()
    )

    if analysis is None:

        raise HTTPException(
            status_code=404,
            detail="Analysis not found",
        )

    return analysis


# =========================================================
# GET RESULTS DIRECTORY
# =========================================================

def get_analysis_results_directory(
    analysis: CCTVAnalysis,
):
    """
    Return the directory containing the
    actual analysis results.json.

    Evidence images are stored beside results.json.
    """

    if not analysis.results_path:

        raise HTTPException(
            status_code=404,
            detail=(
                "Analysis results path is not available."
            ),
        )

    results_path = Path(
        analysis.results_path
    )

    if not results_path.exists():

        raise HTTPException(
            status_code=404,
            detail=(
                "Analysis results file not found."
            ),
        )

    return results_path.parent


# =========================================================
# SAFE EVIDENCE FILENAME
# =========================================================

def get_safe_evidence_filename(
    filename: str,
):
    """
    Prevent directory traversal.

    Only the filename itself is accepted.
    """

    safe_filename = Path(
        filename
    ).name

    if not safe_filename:

        raise HTTPException(
            status_code=400,
            detail="Invalid evidence filename.",
        )

    if safe_filename != filename:

        raise HTTPException(
            status_code=400,
            detail="Invalid evidence filename.",
        )

    return safe_filename


