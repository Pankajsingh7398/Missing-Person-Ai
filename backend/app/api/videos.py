@router.get(
    "/cases/{case_id}/analyses"
)
def get_case_analyses(
    case_id: int,
    db: Session = Depends(get_db),
):
    """
    Return all CCTV analyses belonging
    to a specific missing-person case.
    """

    # -----------------------------------------------------
    # Verify case
    # -----------------------------------------------------

    case = get_case_or_404(
        case_id,
        db,
    )

    # -----------------------------------------------------
    # Get analyses
    # -----------------------------------------------------

    analyses = (
        db.query(CCTVAnalysis)
        .filter(
            CCTVAnalysis.case_id == case_id
        )
        .order_by(
            CCTVAnalysis.created_at.desc()
        )
        .all()
    )

    # -----------------------------------------------------
    # Build response
    # -----------------------------------------------------

    analysis_list = []

    for analysis in analyses:

        analysis_list.append({

            "id":
                analysis.id,

            "analysis_id":
                analysis.analysis_id,

            "video_id":
                analysis.video_id,

            "status":
                analysis.status,

            "potential_matches":
                analysis.potential_matches,

            "confirmed_sightings":
                analysis.confirmed_sightings,

            "best_similarity":
                analysis.best_similarity,

            "created_at":
                (
                    analysis.created_at.isoformat()
                    if analysis.created_at
                    else None
                ),

            "results_path":
                analysis.results_path,
        })

    return {

        "success":
            True,

        "case_id":
            case.id,

        "case_name":
            case.name,

        "count":
            len(analysis_list),

        "analyses":
            analysis_list,
    }


