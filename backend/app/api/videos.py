# GET EVIDENCE GALLERY
# =========================================================

@router.get(
    "/cases/{case_id}/analyses/{analysis_id}/evidence"
)
def get_evidence_gallery(
    case_id: int,
    analysis_id: str,
    db: Session = Depends(get_db),
):
    """
    Return all evidence images belonging
    to an analysis.

    The gallery is generated from the matches
    stored in results.json.
    """

    analysis = get_analysis_or_404(
        case_id,
        analysis_id,
        db,
    )

    # -----------------------------------------------------
    # Load results
    # -----------------------------------------------------

    results = load_results_json(
        Path(
            analysis.results_path
        )
    )

    matches = results.get(
        "matches",
        [],
    )

    sightings = results.get(
        "sightings",
        [],
    )

    # -----------------------------------------------------
    # Build unique evidence list
    # -----------------------------------------------------

    evidence = []

    seen_files = set()

    for match in matches:

        filename = match.get(
            "evidence_image"
        )

        if not filename:
            continue

        filename = Path(
            filename
        ).name

        if filename in seen_files:
            continue

        seen_files.add(
            filename
        )

        evidence.append({

            "filename":
                filename,

            "frame":
                match.get(
                    "frame"
                ),

            "timestamp":
                match.get(
                    "timestamp"
                ),

            "similarity":
                match.get(
                    "similarity"
                ),

            "reference_index":
                match.get(
                    "reference_index"
                ),

            "bounding_box":
                match.get(
                    "bounding_box"
                ),

            "url": (
                f"/api/cases/"
                f"{case_id}/analyses/"
                f"{analysis_id}/evidence/"
                f"{filename}"
            ),

            "is_confirmed":
                False,
        })

    # -----------------------------------------------------
    # Mark confirmed evidence
    # -----------------------------------------------------

    confirmed_files = set()

    for sighting in sightings:

        filename = sighting.get(
            "evidence_image"
        )

        if filename:

            confirmed_files.add(
                Path(
                    filename
                ).name
            )

    for item in evidence:

        if item["filename"] in confirmed_files:

            item["is_confirmed"] = True

    # -----------------------------------------------------
    # Verify physical files
    # -----------------------------------------------------

    results_directory = (
        get_analysis_results_directory(
            analysis
        )
    )

    existing_evidence = []

    for item in evidence:

        evidence_path = (
            results_directory
            / item["filename"]
        )

        if evidence_path.exists():

            existing_evidence.append(
                item
            )

    # -----------------------------------------------------
    # Response
    # -----------------------------------------------------

    return {

        "success":
            True,

        "case_id":
            case_id,

        "analysis_id":
            analysis_id,

        "count":
            len(existing_evidence),

        "evidence":
            existing_evidence,
    }


